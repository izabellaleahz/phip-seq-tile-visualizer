"""
SQLAlchemy database models for PostgreSQL

These models represent the PhIP-seq data structure optimized for queries.
"""

from sqlalchemy import Column, String, Integer, Float, Boolean, Text, ForeignKey, Index, ARRAY
from sqlalchemy.dialects.postgresql import JSONB, TSVECTOR
from sqlalchemy.ext.declarative import declarative_base
from sqlalchemy.orm import relationship

Base = declarative_base()


class Virus(Base):
    """Virus table - main virus metadata"""
    __tablename__ = "viruses"

    id = Column(String(50), primary_key=True)
    name = Column(String(500), nullable=False)
    protein_count = Column(Integer, nullable=False)
    tile_count = Column(Integer, nullable=False)
    unique_tiles = Column(Integer)
    taxon_ids = Column(ARRAY(String), nullable=False)
    host_species = Column(ARRAY(String), nullable=False)

    # Relationship to proteins
    proteins = relationship("Protein", back_populates="virus")

    # Indexes
    __table_args__ = (
        Index("idx_viruses_host", host_species, postgresql_using="gin"),
    )

    def to_dict(self):
        """Convert to dict matching frontend schema"""
        return {
            "id": self.id,
            "name": self.name,
            "proteinCount": self.protein_count,
            "tileCount": self.tile_count,
            "uniqueTiles": self.unique_tiles,
            "taxonIds": self.taxon_ids,
            "hostSpecies": self.host_species,
        }


class Protein(Base):
    """Protein table - protein metadata"""
    __tablename__ = "proteins"

    id = Column(String(100), primary_key=True)
    virus_id = Column(String(50), ForeignKey("viruses.id"), nullable=False)
    virus_name = Column(String(500), nullable=False)
    name = Column(Text, nullable=False)
    name_clean = Column(String(500), nullable=False)
    tile_count = Column(Integer, nullable=False)
    shared_tiles = Column(Integer, nullable=False)
    length = Column(Integer, nullable=False)
    coverage_pct = Column(Float, nullable=False)
    coverage_start = Column(Integer, nullable=False)
    coverage_end = Column(Integer, nullable=False)
    database = Column(String(50))
    x_regions = Column(JSONB)  # [{"start": 10, "end": 20}, ...]

    # Relationships
    virus = relationship("Virus", back_populates="proteins")
    tiles = relationship("TilePosition", back_populates="protein")

    # Indexes
    __table_args__ = (
        Index("idx_proteins_virus", virus_id),
        Index("idx_proteins_coverage", coverage_pct),
    )

    def to_dict(self, include_tiles=False):
        """Convert to dict matching frontend schema"""
        result = {
            "id": self.id,
            "virusId": self.virus_id,
            "virusName": self.virus_name,
            "name": self.name,
            "nameClean": self.name_clean,
            "tileCount": self.tile_count,
            "sharedTiles": self.shared_tiles,
            "length": self.length,
            "coveragePct": self.coverage_pct,
            "coverageStart": self.coverage_start,
            "coverageEnd": self.coverage_end,
            "database": self.database,
            "xRegions": self.x_regions,
        }

        if include_tiles:
            result["tiles"] = [t.to_dict() for t in self.tiles]

        return result


class TilePosition(Base):
    """Tile positions within proteins"""
    __tablename__ = "tile_positions"

    id = Column(Integer, primary_key=True, autoincrement=True)
    tile_id = Column(String(100), nullable=False)
    protein_id = Column(String(100), ForeignKey("proteins.id"), nullable=False)
    start_pos = Column(Integer, nullable=False)
    end_pos = Column(Integer, nullable=False)
    is_shared = Column(Boolean, nullable=False)
    seq = Column(Text, nullable=False)
    dna = Column(Text)

    # Relationship
    protein = relationship("Protein", back_populates="tiles")

    # Indexes
    __table_args__ = (
        Index("idx_tiles_protein", protein_id),
        Index("idx_tiles_tile_id", tile_id),
    )

    def to_dict(self):
        """Convert to dict matching frontend schema"""
        return {
            "id": self.tile_id,
            "start": self.start_pos,
            "end": self.end_pos,
            "isShared": self.is_shared,
            "seq": self.seq,
            "dna": self.dna,
        }


class SearchFTS(Base):
    """Full-text search index (replicates searchDb.ts search_fts table)"""
    __tablename__ = "search_fts"

    id = Column(Integer, primary_key=True, autoincrement=True)
    entry_type = Column(String(20), nullable=False)  # virus, protein, collapsed, virushostdb
    name = Column(Text, nullable=False)
    accession = Column(String(100))
    protein_name = Column(Text)
    taxon_id = Column(String(20))
    ref_id = Column(String(100))
    # search_vector will be generated by PostgreSQL tsvector

    # Indexes
    __table_args__ = (
        Index("idx_search_type", entry_type),
    )

    def to_dict(self):
        """Convert to dict matching frontend SearchResult schema"""
        return {
            "type": self.entry_type,
            "id": self.ref_id or self.accession or str(self.id),
            "name": self.name,
            "accession": self.accession,
            "proteinName": self.protein_name,
            "taxonId": self.taxon_id,
            "refId": self.ref_id,
        }
